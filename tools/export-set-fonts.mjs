// export-set-fonts.mjs — every glyph set's FACE, as one generated table.
//
// The registry's PROVENANCE records which font file each set was rendered
// from; Recto needs the human side of that fact — family name, bold, italic —
// to draw an OCR line as vector text in the same face the reader matched, to
// pick the glyph set for a hand-typed box of a given family, and to preselect
// the text tool's font once a document has been read. Deriving that from set
// names with regexes (`timesbdlin16` → Times bold) went wrong twice; this is
// the registry saying it once.
//
//   node tools/export-set-fonts.mjs          # writes engine/set-fonts.js
//   node tools/export-set-fonts.mjs --check  # exit 1 if the file is stale
//
// engine/set-fonts.js is synced into Recto with the engine (sync-recto.mjs)
// and asserted current by `npm test`. Family names are the ones Recto's font
// catalogue (assets/fonts/fonts.json) uses — the URW faces under their own
// names, not "Times New Roman" for Nimbus Roman: MuPDF's own fonts are what a
// document rendered with them shows, and the catalogue ships those files.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SETS, PROVENANCE } from './glyph-registry.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(REPO, 'engine', 'set-fonts.js');

// font file (as recorded in PROVENANCE) → [family, ...styles]
const FACES = {
  'arial.ttf': ['Arial'], 'arialbd.ttf': ['Arial', 'bold'], 'ariali.ttf': ['Arial', 'italic'],
  'calibri.ttf': ['Calibri'], 'calibrib.ttf': ['Calibri', 'bold'], 'calibrii.ttf': ['Calibri', 'italic'],
  'calibri-jondot.ttf': ['Calibri'], 'calibrib-jondot.ttf': ['Calibri', 'bold'],
  'cambria-w11.ttf': ['Cambria'], 'cambriai.ttf': ['Cambria', 'italic'],
  'cambriab.ttf': ['Cambria', 'bold'], 'cambriaz.ttf': ['Cambria', 'bold', 'italic'],
  'cour.ttf': ['Courier New'], 'courbd.ttf': ['Courier New', 'bold'],
  'georgia.ttf': ['Georgia'],
  'NimbusMonoPS-Regular.cff': ['Nimbus Mono PS'],
  'NimbusRoman-Regular.cff': ['Nimbus Roman'], 'NimbusRoman-Regular-1.12.0.cff': ['Nimbus Roman'],
  'NimbusRoman-Bold.cff': ['Nimbus Roman', 'bold'], 'NimbusRoman-Italic.cff': ['Nimbus Roman', 'italic'],
  'NimbusSans-Regular.cff': ['Nimbus Sans'], 'NimbusSans-Bold.cff': ['Nimbus Sans', 'bold'],
  'times.ttf': ['Times New Roman'], 'timesbd.ttf': ['Times New Roman', 'bold'],
  'timesi.ttf': ['Times New Roman', 'italic'], 'TimesNewRoman8_Clean.ttf': ['Times New Roman'],
  'CENSCBK.TTF': ['Century Schoolbook'], 'SCHLBKB.TTF': ['Century Schoolbook', 'bold'],
  'SCHLBKI.TTF': ['Century Schoolbook', 'italic'],
  'segoeui.ttf': ['Segoe UI'], 'segoeuib.ttf': ['Segoe UI', 'bold'], 'segoeuii.ttf': ['Segoe UI', 'italic'],
  'tahoma.ttf': ['Tahoma'], 'tahomabd.ttf': ['Tahoma', 'bold'],
  'DejaVuSerif.ttf': ['DejaVu Serif'], 'DejaVuSerif-786law.ttf': ['DejaVu Serif'],
  'verdana.ttf': ['Verdana'], 'verdanab.ttf': ['Verdana', 'bold'],
};

export function buildSetFonts() {
  const table = {};
  for (const [name] of SETS) {
    const p = PROVENANCE[name];
    if (!p || p.src === 'corpus' || !p.font) { table[name] = null; continue; }   // page cuts: no face
    const face = FACES[p.font];
    if (!face) throw new Error(`export-set-fonts: no family for font file "${p.font}" (set ${name}) — add it to FACES`);
    const [family, ...styles] = face;
    // plain: the set to pick for a hand-typed box of this family — stock face
    // and stock law, not a producer variant (linear compositor, gray ink, a
    // recreated transport law, a specific font build, a mid-law harvest)
    const plain = (p.src === 'system' || p.src === 'free') && !p.linear && p.ink === undefined &&
      !/law|mid|g\d+_/.test(name);
    table[name] = { family, bold: styles.includes('bold'), italic: styles.includes('italic'),
      file: p.font, sizePx: p.sizePx ?? p.em64 / 64, plain };
  }
  const body = JSON.stringify(table, null, 2).replace(/^/gm, '  ');
  return `// set-fonts.js — GENERATED by tools/export-set-fonts.mjs from the glyph
// registry's PROVENANCE. Do not edit; regenerate. Each glyph set → the face it
// was rendered from: { family, bold, italic, file, sizePx, plain } (plain = the
// stock face under the stock law, the set to pick for a typed box of that
// family), or null for page-cut sets that have no face.
(function (root) {
  'use strict';
  const OCR_SET_FONTS =
${body};
  if (typeof module !== 'undefined' && module.exports) module.exports = OCR_SET_FONTS;
  else root.OCR_SET_FONTS = OCR_SET_FONTS;
})(typeof self !== 'undefined' ? self : this);
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = buildSetFonts();
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (have === want) { console.log('engine/set-fonts.js is current'); process.exit(0); }
    console.log('engine/set-fonts.js is STALE — run: node tools/export-set-fonts.mjs'); process.exit(1);
  }
  writeFileSync(OUT, want);
  console.log(`${OUT}: ${SETS.length} sets (${SETS.filter(([n]) => PROVENANCE[n].src === 'corpus').length} page cuts without a face)`);
}
